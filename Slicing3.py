word = "PYTHON"                         # Stores the word

print(word[0:2])                        # Gets first 2 characters
print(word[1:4])                        # Gets characters from index 1 to 3
print(word[:3])                         # Gets first 3 characters
print(word[3:])                         # Gets characters from index 3 to end
print(word[::-1])                       # Reverses the word